where not exists (select 1 from public.hg_modeles_reponse)
order by v.rang;

/* Journal : création, modification (avant / après) et suppression d'un modèle. Une modification sans changement n'écrit rien. */
create or replace function public.hg_modeles_reponse__audit()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    perform public.hg_admin_audit('modele_reponse_cree', null, new.titre, jsonb_build_object('id', new.id, 'categorie', new.categorie));
  elsif tg_op = 'UPDATE' then
    if (new.titre, new.categorie, new.texte) is distinct from (old.titre, old.categorie, old.texte) then
      perform public.hg_admin_audit('modele_reponse_modifie', null, new.titre, jsonb_build_object('id', new.id,
        'avant', jsonb_build_object('titre', old.titre, 'categorie', old.categorie, 'texte', old.texte),
        'apres', jsonb_build_object('titre', new.titre, 'categorie', new.categorie, 'texte', new.texte)));
    end if;
  else
    perform public.hg_admin_audit('modele_reponse_supprime', null, old.titre,
      jsonb_build_object('id', old.id, 'categorie', old.categorie, 'texte', old.texte));
  end if;
  return null;
end $$;
revoke all on function public.hg_modeles_reponse__audit() from public, anon, authenticated;

drop trigger if exists hg_modeles_reponse_audit on public.hg_modeles_reponse;
create trigger hg_modeles_reponse_audit after insert or update or delete on public.hg_modeles_reponse
  for each row execute function public.hg_modeles_reponse__audit();
drop trigger if exists hg_modeles_reponse_maj on public.hg_modeles_reponse;
create trigger hg_modeles_reponse_maj before update on public.hg_modeles_reponse
  for each row execute function public.set_updated_at();
