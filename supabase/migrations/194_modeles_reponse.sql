-- Modèles de réponse de l'Assistance (idée 99) : réponses types que le Staff insère dans la zone de réponse d'une demande,
-- puis adapte avant l'envoi. {prenom} est remplacé par le pseudo du membre côté site (admin/support-modeles.js).
--
-- Droit « support » pour lire et pour écrire, comme hg_support et hg_ideas : le site passe par la table, sans RPC.
-- L'envoi reste celui de l'Assistance : un modèle n'envoie jamais rien tout seul.
-- Les bornes sont en base : 60 caractères pour le titre, 30 pour « Rangé dans » (facultatif), 2 000 pour le texte.
-- Chaque écriture est notée dans hg_admin_log par un déclencheur (même approche que hg_badges, migration 076) : aucune
-- écriture de la table ne peut y échapper, et hg_admin_audit reste fermée aux comptes.
--
-- Rejouable : les 5 modèles de départ ne sont insérés que si la table est vide. Une reprise ne remet donc ni un texte
-- modifié ni un modèle supprimé par le Staff.

create table if not exists public.hg_modeles_reponse (
  id         bigint generated by default as identity primary key,
  titre      text not null check (titre ~ '\S' and char_length(titre) <= 60),
  categorie  text not null default '' check (char_length(categorie) <= 30),
  texte      text not null check (texte ~ '\S' and char_length(texte) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.hg_modeles_reponse is 'Idée 99 (migration 194) : réponses types de l''Assistance. Lecture et écriture : droit support. Écritures journalisées par hg_modeles_reponse__audit.';

alter table public.hg_modeles_reponse enable row level security;
revoke all on public.hg_modeles_reponse from public, anon, authenticated;
grant select, insert, update, delete on public.hg_modeles_reponse to authenticated;
drop policy if exists hg_modeles_reponse_support on public.hg_modeles_reponse;
create policy hg_modeles_reponse_support on public.hg_modeles_reponse for all to authenticated
  using (public.hg_has_perm('support')) with check (public.hg_has_perm('support'));

insert into public.hg_perm_tables (tbl, perm) values ('hg_modeles_reponse', 'support')
  on conflict (tbl) do update set perm = excluded.perm;

-- Les 5 modèles de la maquette validée, avant le déclencheur : l'installation n'écrit rien au journal.
insert into public.hg_modeles_reponse (titre, categorie, texte)
select v.titre, v.categorie, v.texte
from (values
  (1, 'Mot de passe oublié', 'Connexion', 'Salut {prenom}, tu peux choisir un nouveau mot de passe depuis la page de connexion, avec « Mot de passe oublié ». Si le mail n’arrive pas, regarde dans tes indésirables et dis-moi.'),
  (2, 'Bug bien reçu', 'Bug', 'Merci {prenom}, on a bien reçu ton signalement. On regarde ça et on te tient au courant ici.'),
  (3, 'Carte manquante', 'Cartes', 'Salut {prenom}, peux-tu me donner le nom de la carte et le moment où elle a disparu ? Je vérifie ton inventaire.'),
  (4, 'Accès à une page', 'Compte', 'Salut {prenom}, je viens de vérifier tes accès. Déconnecte-toi puis reconnecte-toi, la page devrait apparaître.'),
  (5, 'Demande traitée', 'Clôture', 'C’est réglé de notre côté, {prenom}. Si ça recommence, réponds simplement ici.')
